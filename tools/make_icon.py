#!/usr/bin/env python3
"""Generate the PoorDS4 notification icon.

Produces payload/assets/poor_ds4_icon.png: a 200x200 RGBA icon (PlayStation
blue rounded square with a white DualShock silhouette) used as the native
system toast icon. Pure standard library, reproducible:

    python3 tools/make_icon.py

Then regenerate the embedded copy with:

    python3 tools/make_icon.py --header
"""
import os
import struct
import sys
import zlib

SIZE = 200
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PNG_PATH = os.path.join(ROOT, "payload", "assets", "poor_ds4_icon.png")
HEADER_PATH = os.path.join(ROOT, "payload", "assets", "poor_ds4_icon.h")

# Playstation blue gradient, top to bottom.
TOP = (0x00, 0x5F, 0xBD)
BOTTOM = (0x1E, 0x9B, 0xFF)
PAD = (0xFF, 0xFF, 0xFF)


def sd_round_rect(px, py, cx, cy, hw, hh, radius):
    qx = abs(px - cx) - (hw - radius)
    qy = abs(py - cy) - (hh - radius)
    ax = qx if qx > 0.0 else 0.0
    ay = qy if qy > 0.0 else 0.0
    outside = (ax * ax + ay * ay) ** 0.5
    inside = min(max(qx, qy), 0.0)
    return outside + inside - radius


def sd_circle(px, py, cx, cy, radius):
    dx = px - cx
    dy = py - cy
    return (dx * dx + dy * dy) ** 0.5 - radius


def sd_capsule(px, py, ax, ay, bx, by, radius):
    pax, pay = px - ax, py - ay
    bax, bay = bx - ax, by - ay
    length = bax * bax + bay * bay
    h = 0.0
    if length > 0.0:
        h = (pax * bax + pay * bay) / length
        h = 0.0 if h < 0.0 else (1.0 if h > 1.0 else h)
    dx = pax - bax * h
    dy = pay - bay * h
    return (dx * dx + dy * dy) ** 0.5 - radius


def smin(a, b, k=4.0):
    h = 0.5 + 0.5 * (b - a) / k
    h = 0.0 if h < 0.0 else (1.0 if h > 1.0 else h)
    return b * (1.0 - h) + a * h - k * h * (1.0 - h)


def coverage(distance):
    """One pixel wide analytic anti-aliasing band."""
    value = 0.5 - distance
    return 0.0 if value < 0.0 else (1.0 if value > 1.0 else value)


def pad_distance(px, py):
    body = sd_round_rect(px, py, 100.0, 103.0, 58.0, 25.0, 22.0)
    left = sd_capsule(px, py, 60.0, 106.0, 45.0, 132.0, 19.0)
    right = sd_capsule(px, py, 140.0, 106.0, 155.0, 132.0, 19.0)
    return smin(smin(body, left), right)


def cutout_distance(px, py):
    dpad = min(
        sd_round_rect(px, py, 72.0, 100.0, 13.5, 4.6, 2.4),
        sd_round_rect(px, py, 72.0, 100.0, 4.6, 13.5, 2.4))
    touchpad = sd_round_rect(px, py, 100.0, 82.5, 17.0, 6.2, 4.0)
    buttons = min(
        sd_circle(px, py, 118.5, 100.0, 4.7),
        sd_circle(px, py, 137.5, 100.0, 4.7),
        sd_circle(px, py, 128.0, 90.5, 4.7),
        sd_circle(px, py, 128.0, 109.5, 4.7))
    sticks = min(
        sd_circle(px, py, 86.0, 116.0, 8.6),
        sd_circle(px, py, 114.0, 116.0, 8.6))
    return min(dpad, min(touchpad, min(buttons, sticks)))


def render():
    rows = []
    for y in range(SIZE):
        row = bytearray()
        py = y + 0.5
        for x in range(SIZE):
            px = x + 0.5
            background = coverage(sd_round_rect(px, py, 100.0, 100.0,
                                                100.0, 100.0, 46.0))
            if background <= 0.0:
                row += bytes((0, 0, 0, 0))
                continue
            mix = py / SIZE
            red = TOP[0] + (BOTTOM[0] - TOP[0]) * mix
            green = TOP[1] + (BOTTOM[1] - TOP[1]) * mix
            blue = TOP[2] + (BOTTOM[2] - TOP[2]) * mix
            pad = coverage(pad_distance(px, py))
            if pad > 0.0:
                hole = coverage(cutout_distance(px, py))
                pad *= 1.0 - hole
                red = red + (PAD[0] - red) * pad
                green = green + (PAD[1] - green) * pad
                blue = blue + (PAD[2] - blue) * pad
            alpha = int(background * 255.0 + 0.5)
            row += bytes((int(red + 0.5), int(green + 0.5), int(blue + 0.5),
                          alpha))
        rows.append(bytes(row))
    return rows


def chunk(tag, payload):
    return (struct.pack(">I", len(payload)) + tag + payload +
            struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF))


def write_png(rows, path):
    raw = b"".join(b"\x00" + row for row in rows)
    data = (b"\x89PNG\r\n\x1a\n" +
            chunk(b"IHDR", struct.pack(">IIBBBBB", SIZE, SIZE, 8, 6, 0, 0, 0)) +
            chunk(b"IDAT", zlib.compress(raw, 9)) +
            chunk(b"IEND", b""))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as handle:
        handle.write(data)
    return len(data)


def write_header(png_bytes, path):
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-or-later",
        " * Generated by tools/make_icon.py --header. Do not edit by hand:",
        " * regenerate from payload/assets/poor_ds4_icon.png instead. */",
        "#pragma once",
        "",
        "#define POORDS4_ICON_PNG_SIZE %uu" % len(png_bytes),
        "",
        "static const unsigned char g_poor_ds4_icon_png[] = {",
    ]
    for offset in range(0, len(png_bytes), 12):
        block = png_bytes[offset:offset + 12]
        lines.append("    " + " ".join("0x%02x," % byte for byte in block))
    lines.append("};")
    lines.append("")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    return len(png_bytes)


def main():
    rows = render()
    size = write_png(rows, PNG_PATH)
    print(f"wrote {PNG_PATH} ({size} bytes, {SIZE}x{SIZE} RGBA)")
    if "--header" in sys.argv:
        with open(PNG_PATH, "rb") as handle:
            png_bytes = handle.read()
        write_header(png_bytes, HEADER_PATH)
        print(f"wrote {HEADER_PATH} ({len(png_bytes)} bytes)")


if __name__ == "__main__":
    main()
